_CAT_COMPILED = {cat: re.compile("|".join(re.escape(k) for k in kws)) for cat, kws in _CATEGORY_KEYWORDS.items()}


def parse_text(text: str) -> dict:
    text = text.strip()
    if not text:
        return {"type": None, "amount": 0, "category": None, "note": None, "confidence": 0}

    # 1. 提取金额
    amount = 0.0
    for pattern, extractor in _AMOUNT_PATTERNS:
        match = re.search(pattern, text)
        if match:
            amount = extractor(match.groups())
            break

    # 2. 判断类型
    rectype = "expense"
    for t, keywords in _TYPE_KEYWORDS.items():
        for kw in keywords:
            if kw in text:
                rectype = t
                break

    # 3. 匹配分类: 按匹配关键词数 + 关键词长度加权
    category = None
    best_score = 0
    for cat, regex in _CAT_COMPILED.items():
        matches = regex.findall(text)
        if matches:
            score = sum(len(m) for m in matches)  # 长关键词权重更高
            if score > best_score:
                best_score = score
                category = cat

    # 4. 如果是收入但没有匹配到特定收入分类，给默认值
    if rectype == "income" and category is None:
        category = "其他收入"
    elif rectype == "savings" and category is None:
        category = "其他存钱"

    note = text[:200]
    confidence = 0.3
    if amount > 0: confidence += 0.4
    if category: confidence += 0.2
    confidence = min(confidence, 1.0)

    return {
        "type": rectype,
        "amount": round(amount, 2),
        "category": category,
        "note": note,
        "confidence": round(confidence, 2),
    }
